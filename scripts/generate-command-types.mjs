import { readdirSync, readFileSync, statSync, writeFileSync } from 'fs';
import { join } from 'path';

const SOURCE_DIR = 'src-tauri/src';
const OUT = 'src/renderer/src/tauriCommands.ts';

// Injected by Tauri from its own container, never sent from the frontend. Matched on the
// type, because the parameter can be called anything.
const INJECTED =
  /\b(State|AppHandle|Window|WebviewWindow|Webview)\s*<|\b(AppHandle|Window|WebviewWindow)\b/;

function rustFiles(dir) {
  return readdirSync(dir)
    .sort()
    .flatMap((entry) => {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) return rustFiles(path);
      return path.endsWith('.rs') ? [path] : [];
    });
}

function camel(name) {
  return name.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());
}

function tsType(rust) {
  const type = rust
    .trim()
    .replace(/^&/, '')
    .replace(/'_,?\s*/g, '');
  const option = type.match(/^Option<(.+)>$/);
  if (option) return `(${tsType(option[1])} | null)`;
  const vec = type.match(/^Vec<(.+)>$/);
  if (vec) return `${tsType(vec[1])}[]`;
  const map = type.match(/^(?:std::collections::)?HashMap<\s*String\s*,\s*(.+)>$/);
  if (map) return `Record<string, ${tsType(map[1])}>`;
  const array = type.match(/^\[(.+);\s*(\d+)\]$/);
  if (array) return `[${Array(Number(array[2])).fill(tsType(array[1])).join(', ')}]`;
  if (/^(String|str)$/.test(type)) return 'string';
  if (/^(f32|f64|u8|u16|u32|u64|i8|i16|i32|i64|usize|isize)$/.test(type)) return 'number';
  if (type === 'bool') return 'boolean';
  return 'unknown';
}

function returnType(rust) {
  if (!rust) return 'void';
  const result = rust.match(/^Result<\s*([\s\S]*?)\s*(?:,\s*[\s\S]+)?>$/);
  if (result) return result[1] === '()' ? 'void' : tsType(result[1]);
  return rust === '()' ? 'void' : tsType(rust);
}

function splitParams(text) {
  const out = [];
  let depth = 0;
  let current = '';
  for (const char of text) {
    if (char === '<' || char === '(' || char === '[') depth++;
    if (char === '>' || char === ')' || char === ']') depth--;
    if (char === ',' && depth === 0) {
      out.push(current);
      current = '';
      continue;
    }
    current += char;
  }
  if (current.trim()) out.push(current);
  return out;
}

const commands = [];
for (const file of rustFiles(SOURCE_DIR)) {
  const source = readFileSync(file, 'utf8');
  const pattern =
    /#\[tauri::command\][\s\S]*?fn\s+(\w+)\s*\(([\s\S]*?)\)\s*(?:->\s*([^{]+?))?\s*\{/g;
  let match;
  while ((match = pattern.exec(source)) !== null) {
    const [, name, rawParams, rawReturn] = match;
    const args = splitParams(rawParams)
      .map((param) => param.trim())
      .filter(Boolean)
      .map((param) => {
        const colon = param.indexOf(':');
        return { name: param.slice(0, colon).trim(), type: param.slice(colon + 1).trim() };
      })
      .filter((param) => param.name && !INJECTED.test(param.type));
    commands.push({ name, args, returns: returnType(rawReturn?.trim()) });
  }
}
commands.sort((left, right) => left.name.localeCompare(right.name));

const entries = commands
  .map(({ name, args, returns }) => {
    const shape = args.length
      ? `{ ${args.map((arg) => `${camel(arg.name)}: ${tsType(arg.type)}`).join('; ')} }`
      : 'Record<string, never>';
    return `  ${name}: { args: ${shape}; returns: ${returns} };`;
  })
  .join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/generate-command-types.mjs from #[tauri::command] signatures.
// Run \`yarn generate:commands\` after adding or changing one.
import { invoke } from '@tauri-apps/api/core';

type Commands = {
${entries}
};

export type CommandName = keyof Commands;

export function call<Name extends CommandName>(
  command: Name,
  ...args: Commands[Name]['args'] extends Record<string, never>
    ? []
    : [Commands[Name]['args']]
): Promise<Commands[Name]['returns']> {
  return invoke(command, args[0]);
}
`
);

console.log(`${commands.length} commands -> ${OUT}`);
